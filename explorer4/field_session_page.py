"""One preparation list for the physical session and its metric print targets."""

from fastapi.responses import FileResponse
from nicegui import app, ui

from .paths import ROOT


def install():
    @app.get("/api/workspace/field-targets.pdf")
    def print_pack():
        return FileResponse(
            ROOT / "assets/field-targets-A4.pdf",
            media_type="application/pdf",
            filename="Explorer-4-field-targets-A4.pdf",
        )

    @ui.page("/field-session")
    def page():
        ui.dark_mode().enable()
        with ui.column().classes("w-full max-w-3xl mx-auto p-5 gap-3"):
            ui.link("Центр экспериментов", "/workspace")
            ui.label("Подготовка к физической проверке").classes("text-3xl font-bold")
            ui.label(
                "Для симуляции, очереди обучения и просмотра записей подготовка площадки не требуется."
            )
            ui.label("Что взять за один раз").classes("text-xl font-medium")
            ui.label(
                "Линейка или рулетка, малярная лента, угольник или транспортир, кубик и материал для ширмы. Для настольной перекладки также понадобится коробка."
            )
            ui.link(
                "Один PDF для печати · A4, 100%, односторонняя печать",
                "/api/workspace/field-targets.pdf",
            )
            ui.label(
                "Страница 1 — совместный подъезд. Большой чёрный квадрат 180 мм, нижний 36 мм. Можно показать эту страницу на неподвижном мониторе в том же измеренном масштабе. Если на кубике SO-101 уже есть AprilTag 36h11 №1, его можно использовать после измерения чёрной стороны. На странице 2 есть запасной вариант — ArUco №7 со стороной 20 мм. Достаточно одной копии."
            )
            ui.link("Мишень на экране с настройкой масштаба", "/peer-dock-real/screen")
            ui.label("1. Совместный подъезд Tank и ROSMASTER").classes(
                "text-xl font-medium"
            )
            ui.label(
                "Отметьте переднюю ось Tank и центры обеих машин при STOP. Если ROSMASTER не определяется на общей карте, измерьте его смещение вперёд и влево от центра Tank и угол между их передними осями. Введите эти три числа на странице совместного подъезда. После подтверждения положения лидарами закрепите мишень вертикально. Обе припаркованные камеры должны сначала видеть обе метки. Снимите кадры, затем перенесите мишень вдоль той же стены минимум на 10 см и повторите измерение по инструкции на странице двух камер. Если не определилась общая карта или вторая точка не прошла проверку, мастер покажет причину."
            )
            ui.label(
                "Отметьте лентой исходные положения и направления машин, крест для центра Tank в 277 мм от мишени и ось курса к стене. В расстановке A откройте обзор Tank, в B закройте его ширмой, сохранив обзор ROSMASTER и свободный путь. Для каждой попытки восстановите метки старта. После STOP и 0,5 с неподвижности измерьте отклонение центра и угол относительно разметки. Порядок восьми попыток хранится в панели."
            )
            ui.link("Две камеры, разметка и полевой журнал", "/peer-dock-real")
            ui.label("2. Подъём кубика рукой ROSMASTER").classes("text-xl font-medium")
            ui.label(
                "Зафиксируйте шасси и камеру в позе обзора, указанной в мастере. Измерьте ширину кубика и открытого захвата. Отметьте центр кубика в трёх точках треугольника для настройки и ещё в двух для проверки. Сначала мастер сравнит ручные координаты с камерой."
            )
            ui.label(
                "Для следующего допуска нужны три независимые проверочные записи в проверенной позе камеры. Мастер создаст их в отдельной диагностической серии. Если проверка пройдена, положите тот же кубик в четвёртую измеренную точку и откройте из мастера одиночную пробу. Отдельно укажите видимый отрыв от опоры и длительность удержания кубика до STOP."
            )
            ui.link(
                "Мастер камеры и регистрации показов", "/rosmaster/grasp-calibration"
            )
            ui.label("3. Настольная рука SO-101 · дополнительный опыт").classes(
                "text-xl font-medium"
            )
            ui.label(
                "Проверьте, видит ли верхняя камера существующую красную метку на белом фоне на губке захвата в её откалиброванном месте. Для измерения кубика выберите в параметрах сбора его метку (AprilTag №1 или ArUco №7) и введите длину чёрной стороны. Результат проверки камеры виден в центре экспериментов."
            )
            ui.link("Параметры метки кубика SO-101", "/recording/collect?task=so101_pick_place")
            ui.link("Проверка камеры SO-101", "/workspace#field-checks")
            ui.label(
                "Оставьте AprilTag №1 на том же 29-мм кубике. При STOP покажите его камере ROSMASTER и проверьте, виден ли №1 на сохранённом RGB. Исходный кадр SO-101 уже есть."
            )
            ui.link("Проверить метку кубика на ROSMASTER", "/rosmaster/sensors?object_marker=true")
